import os
import re
from dotenv import load_dotenv
from openai import OpenAI, APIError

# load configurations from the .env file
load_dotenv()

# create a client that communicates with ollama (AI Model)
client = OpenAI(
    base_url=os.getenv("BASE_URL"),
    api_key=os.getenv("API_KEY"),
    timeout=180.0,  # Increased timeout for reasoning models
)

print("*" * 40)
print("Start Conversation Day 02")
print("*" * 40)

messages_history = []
user_input = input("You: ")


def parse_thinking_and_content(full_content):
  """Extracts <think>...</think> blocks from the model's response."""
  if not full_content:
    return "", ""

  # Search for <think> tags generated by reasoning models
  think_match = re.search(
      r"<think>(.*?)</think>", full_content, re.DOTALL | re.IGNORECASE
  )

  if think_match:
    thinking_process = think_match.group(1).strip()
    # Remove the think block from the content to get the final answer
    final_answer = re.sub(
        r"<think>.*?</think>", "", full_content, flags=re.DOTALL | re.IGNORECASE
    ).strip()
    return thinking_process, final_answer
  else:
    return "", full_content.strip()


try:
  while user_input != "quit":
    messages_history.append({"role": "user", "content": user_input})

    print("\nAI is thinking...", end="\r")

    # Send a question to the AI Model
    response = client.chat.completions.create(
        model=os.getenv("MODEL"),
        messages=messages_history,
        max_tokens=8192,  # Increased to prevent token exhaustion during thinking
        extra_body={
            "options": {
                "num_predict": 8192,  # Give enough room for both thinking and answer
                "temperature": (
                    0.3
                ),  # Lower temperature reduces repeating/hanging loops
            }
        },
    )

    # Safely display the response content
    message_content = response.choices[0].message.content

    if message_content:
      # Parse the thinking tags from the final answer
      thinking, answer = parse_thinking_and_content(message_content)

      if thinking:
        print("\n" + "=" * 10 + " 🧠 MODEL THINKING PROCESS " + "=" * 10)
        print(thinking)
        print("=" * 45 + "\n")

      print(f"AI: {answer}")

      # IMPORTANT: Append the *original, full message_content* (with <think> tags)
      # to the history so the model maintains proper conversational context.
      messages_history.append({"role": "assistant", "content": message_content})
    else:
      print(
          "\nReceived an empty response from the model. (Try increasing"
          " max_tokens / num_predict further)"
      )

    print("\n" + "-" * 40)
    user_input = input("You: ")

except APIError as e:
  print(f"\nOpenAI API Error: {e}")
except Exception as e:
  print(f"\nAn unexpected error occurred: {e}")